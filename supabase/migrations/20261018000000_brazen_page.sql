-- Homepage "What's new" feature (type = 'newItem', id = 1) and food gallery
-- (type = 'foodImg', ordered by img_display_order desc), plus their public
-- image buckets. Originally created in the dashboard; captured here so a fresh
-- project can be set up from migrations alone.

create table if not exists public.brazen_page (
  id bigint generated by default as identity primary key,
  created_at timestamptz not null default now(),
  img_url text,
  title text,
  description text,
  type text,
  is_displayed boolean,
  img_display_order integer unique,
  menu_display_order bigint unique,
  file_path text,
  img_filename text,
  updated_at timestamptz
);

alter table public.brazen_page enable row level security;

create policy "brazen_page: anyone can read"
  on public.brazen_page for select
  using (true);

create policy "brazen_page: staff can manage"
  on public.brazen_page for all to authenticated
  using (true) with check (true);

insert into storage.buckets (id, name, public)
values ('brazen_page', 'brazen_page', true), ('foodPhoto', 'foodPhoto', true)
on conflict (id) do nothing;

create policy "website photos: anyone can read"
  on storage.objects for select
  using (bucket_id in ('brazen_page', 'foodPhoto'));
